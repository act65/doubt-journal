def parse(text: str) -> list[str]:
    return [line for line in text.strip("\n").splitlines()]


def pixels(key: str) -> list[list[str]]:
    canvas = [["."] * SIZE for _ in range(SIZE)]
    for n, layer in enumerate(ICONS[key]["layers"]):
        grid, dx, dy = (layer, 0, 0) if isinstance(layer, str) else layer
        rows = parse(grid)
        if n == 0 and (len(rows) != SIZE or any(len(r) != SIZE for r in rows)):
            sys.exit(f"{key}: base layer must be {SIZE}x{SIZE}, got "
                     f"{[len(r) for r in rows]} wide over {len(rows)} rows")
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == ".":
                    continue
                if ch not in PALETTE:
                    sys.exit(f"{key}: unknown colour {ch!r} at ({x + dx}, {y + dy})")
                canvas[y + dy][x + dx] = ch
    return canvas


def svg(key: str) -> str:
    canvas = pixels(key)
    by_colour: dict[str, list[str]] = {}
    for y, row in enumerate(canvas):
        for x, ch in enumerate(row):
            if ch != ".":
                by_colour.setdefault(PALETTE[ch], []).append(f"M{x} {y}h1v1h-1z")
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" '
        f'shape-rendering="crispEdges">',
        f"<!-- {key}: {ICONS[key]['what']}. Generated by scripts/badge_icons.py; edit the grid "
        f"there. -->",
    ]
    lines += [f'<path fill="{colour}" d="{"".join(d)}"/>' for colour, d in by_colour.items()]
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if any svg is stale")
    args = ap.parse_args()

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from score import PAPER_BADGES  # noqa: E402

    keys = [b["key"] for b in PAPER_BADGES]
    missing = [k for k in keys if k not in ICONS]
    unknown = [k for k in ICONS if k not in keys]
    if unknown:
        print(f"no such badge: {', '.join(unknown)}", file=sys.stderr)
        return 1

    stale = []
    OUT.mkdir(parents=True, exist_ok=True)
    for key in ICONS:
        path, text = OUT / f"{key}.svg", svg(key)
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(key)
        if not args.check:
            path.write_text(text, encoding="utf-8")

    if missing:
        print(f"no icon yet (star instead): {', '.join(missing)}", file=sys.stderr)
    if args.check:
        if stale:
            print(f"stale icons: {', '.join(stale)} — run python scripts/badge_icons.py",
                  file=sys.stderr)
        return 1 if stale or missing else 0
    print(f"{len(ICONS)} icons, {len(stale)} rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
