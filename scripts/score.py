#!/usr/bin/env python3
"""Score the journal.

Reads every paper in ``_papers/*/index.md`` plus the rules in ``_data/gamify.yml`` and writes
the derived scoreboard to ``_data/stats.yml``. Jekyll does no arithmetic — it just renders what
this script computed, so the numbers on the site are reproducible offline and land in git as a
diff you can read (``xp: 16 -> 24``).

    python scripts/score.py            # recompute, write, print the summary
    python scripts/score.py --check    # fail if _data/stats.yml is stale (used by CI)

Also regenerates the per-tag stub pages in ``tags/`` so every tag has a real URL.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PAPERS = ROOT / "_papers"
DATA = ROOT / "_data"
TAGS_DIR = ROOT / "tags"

STAMP = "# Generated by scripts/score.py — do not edit by hand."


# --------------------------------------------------------------------------- loading


def read_front_matter(path: Path) -> tuple[dict, str]:
    """Split a Jekyll document into its YAML front matter and its body."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        raise ValueError(f"{path} has no front matter")
    _, fm, body = text.split("---", 2)
    return yaml.safe_load(fm) or {}, body


def as_date(value) -> dt.date | None:
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    if isinstance(value, str):
        try:
            return dt.date.fromisoformat(value.strip())
        except ValueError:
            return None
    return None


def load_papers() -> list[dict]:
    papers = []
    for index in sorted(PAPERS.glob("*/index.md")):
        fm, body = read_front_matter(index)
        # Drafts are scaffolding: excluded from the scoreboard, and `published: false` keeps
        # Jekyll from rendering them too. Neither counts until you say it does.
        if fm.get("draft") or fm.get("published") is False:
            continue
        fm["slug"] = index.parent.name
        fm["read_date"] = as_date(fm.get("read"))
        fm["words"] = len(body.split())
        fm["sections"] = re.findall(r"^##\s+(.+?)\s*$", body, re.M)
        fm["body"] = body
        fm["tags"] = fm.get("tags") or []
        fm["notebooks"] = fm.get("notebooks") or []
        fm["related"] = fm.get("related") or []
        papers.append(fm)
    return papers


# --------------------------------------------------------------------------- helpers


def normalise_url(url: str | None) -> str | None:
    """Collapse the ways the same paper gets linked, so backlog entries match papers.

    arXiv is the case that actually bites: /abs/2308.07037, /pdf/2308.07037v2 and
    arxiv.org/abs/2308.07037/ are all one paper.
    """
    if not url:
        return None
    u = url.strip().lower().rstrip("/")
    u = re.sub(r"^https?://", "", u)
    u = re.sub(r"^www\.", "", u)
    arxiv = re.search(r"arxiv\.org/(?:abs|pdf)/([^/?#]+)", u)
    if arxiv:
        return "arxiv:" + re.sub(r"v\d+$", "", arxiv.group(1)).removesuffix(".pdf")
    return u


def iso_week(date: dt.date) -> str:
    year, week, _ = date.isocalendar()
    return f"{year}-W{week:02d}"


def week_start(date: dt.date) -> dt.date:
    return date - dt.timedelta(days=date.isoweekday() - 1)


def tag_meta(slug: str, tags_cfg: dict) -> dict:
    meta = tags_cfg.get(slug) or {}
    return {
        "slug": slug,
        "label": meta.get("label") or slug.replace("-", " ").capitalize(),
        "kind": meta.get("kind") or "other",
    }


# --------------------------------------------------------------------------- scoring


def score(papers, gamify, tags_cfg, backlog, today: dt.date) -> dict:
    depth_cfg = gamify.get("depth") or {}
    threshold = gamify.get("accept_threshold", 5)

    def xp_of(paper) -> int:
        return int((depth_cfg.get(paper.get("depth")) or {}).get("xp", 0))

    def status_of(paper) -> str:
        rating = paper.get("rating")
        if rating is None:
            return "under-review"
        return "accepted" if rating >= threshold else "rejected"

    total_xp = sum(xp_of(p) for p in papers)

    # Rank: the highest threshold we have passed, and how far to the next one.
    ranks = sorted(gamify.get("ranks") or [], key=lambda r: r["at"])
    current = ranks[0] if ranks else {"at": 0, "name": "Unranked"}
    following = None
    for rank in ranks:
        if total_xp >= rank["at"]:
            current = rank
        else:
            following = rank
            break
    if following:
        span = following["at"] - current["at"]
        pct = round(100 * (total_xp - current["at"]) / span) if span else 100
        next_rank = {
            "name": following["name"],
            "at": following["at"],
            "remaining": following["at"] - total_xp,
            "pct": pct,
        }
    else:
        next_rank = None

    statuses = Counter(status_of(p) for p in papers)

    by_depth = []
    for slug, cfg in depth_cfg.items():
        matching = [p for p in papers if p.get("depth") == slug]
        by_depth.append(
            {
                "slug": slug,
                "label": cfg.get("label", slug),
                "xp_each": cfg.get("xp", 0),
                "count": len(matching),
                "xp": sum(xp_of(p) for p in matching),
            }
        )

    tag_counts = Counter(t for p in papers for t in p["tags"])
    by_tag = sorted(
        ({**tag_meta(slug, tags_cfg), "count": n} for slug, n in tag_counts.items()),
        key=lambda t: (-t["count"], t["slug"]),
    )

    by_year = [
        {"year": year, "count": n}
        for year, n in sorted(Counter(p["year"] for p in papers if p.get("year")).items())
    ]
    ratings = [
        {"rating": r, "count": n}
        for r, n in sorted(Counter(p["rating"] for p in papers if p.get("rating") is not None).items())
    ]

    # ---- streaks, measured in ISO weeks with at least one paper finished
    read_dates = [p["read_date"] for p in papers if p["read_date"]]
    weeks = Counter(iso_week(d) for d in read_dates)

    this_week = week_start(today)
    # One week of grace: finishing nothing yet this week does not kill a live streak.
    cursor = this_week if iso_week(this_week) in weeks else this_week - dt.timedelta(days=7)
    streak = 0
    while iso_week(cursor) in weeks:
        streak += 1
        cursor -= dt.timedelta(days=7)

    best, run, previous = 0, 0, None
    for start in sorted({week_start(d) for d in read_dates}):
        run = run + 1 if previous and (start - previous).days == 7 else 1
        best, previous = max(best, run), start

    recent = []
    for i in range(25, -1, -1):
        start = this_week - dt.timedelta(days=7 * i)
        recent.append({"week": iso_week(start), "count": weeks.get(iso_week(start), 0)})

    # ---- annual target
    target = gamify.get("annual_target", 52)
    this_year = sum(1 for d in read_dates if d.year == today.year)
    elapsed = (today - dt.date(today.year, 1, 1)).days + 1
    days_in_year = (dt.date(today.year, 12, 31) - dt.date(today.year, 1, 1)).days + 1
    expected = target * elapsed / days_in_year
    year_stats = {
        "value": today.year,
        "read": this_year,
        "target": target,
        "pct": round(100 * this_year / target) if target else 0,
        "expected_by_now": round(expected, 1),
        "ahead_by": round(this_year - expected, 1),
    }

    # ---- backlog coverage
    done_urls = {normalise_url(p.get("ref")) for p in papers} - {None}
    done_titles = {(p.get("title") or "").strip().lower() for p in papers}
    per_tag = defaultdict(lambda: {"total": 0, "cleared": 0})
    cleared_total = starred_open = 0
    for entry in backlog:
        hit = normalise_url(entry.get("url")) in done_urls or (
            entry.get("title", "").strip().lower() in done_titles
        )
        bucket = per_tag[entry.get("tag", "other")]
        bucket["total"] += 1
        if hit:
            bucket["cleared"] += 1
            cleared_total += 1
        elif entry.get("starred"):
            starred_open += 1

    backlog_by_tag = sorted(
        (
            {
                **tag_meta(slug, tags_cfg),
                "total": v["total"],
                "cleared": v["cleared"],
                "pct": round(100 * v["cleared"] / v["total"]) if v["total"] else 0,
            }
            for slug, v in per_tag.items()
        ),
        key=lambda t: (-t["total"], t["slug"]),
    )

    backlog_stats = {
        "total": len(backlog),
        "cleared": cleared_total,
        "open": len(backlog) - cleared_total,
        "pct": round(100 * cleared_total / len(backlog)) if backlog else 0,
        "starred_open": starred_open,
        "by_tag": backlog_by_tag,
    }

    stats = {
        "papers": len(papers),
        "xp": total_xp,
        "rank": {"name": current.get("name"), "at": current.get("at", 0)},
        "next_rank": next_rank,
        "accepted": statuses["accepted"],
        "rejected": statuses["rejected"],
        "under_review": statuses["under-review"],
        "by_depth": by_depth,
        "by_tag": by_tag,
        "by_year": by_year,
        "ratings": ratings,
        "year": year_stats,
        "streak": {"current": streak, "best": best, "weeks": recent},
        "backlog": backlog_stats,
    }
    stats["badges"] = award(papers, stats, gamify, tags_cfg, xp_of, status_of)
    return stats


def award(papers, stats, gamify, tags_cfg, xp_of, status_of) -> list[dict]:
    """Rule-based badges. Each returns (earned, detail) where detail shows progress."""
    depth_cfg = gamify.get("depth") or {}
    deep = [p for p in papers if p.get("depth") in ("rebuilt", "extended")]
    weeks = Counter(iso_week(p["read_date"]) for p in papers if p["read_date"])
    topics = {
        t
        for p in papers
        for t in p["tags"]
        if (tags_cfg.get(t) or {}).get("kind") == "topic"
    }
    same_year = [p for p in papers if p["read_date"] and p.get("year") == p["read_date"].year]
    longest = max((p["words"] for p in papers), default=0)
    most_related = max((len(p["related"]) for p in papers), default=0)
    busiest = max(weeks.values(), default=0)
    swept = [t for t in stats["backlog"]["by_tag"] if t["total"] and t["cleared"] == t["total"]]
    oldest = min((p["year"] for p in papers if p.get("year")), default=None)

    def badge(name, blurb, have, need, unit=""):
        return {
            "name": name,
            "blurb": blurb,
            "earned": have >= need,
            "detail": f"{min(have, need)} / {need}{unit}",
        }

    return [
        badge("First Blood", "Review one paper.", len(papers), 1),
        badge("Reproducer", "Rebuild five papers from scratch.", len(deep), 5),
        badge(
            "Deep Diver",
            "Take one paper further than its authors did.",
            sum(1 for p in papers if p.get("depth") == "extended"),
            1,
        ),
        badge(
            "Archivist",
            "Review something published before 2000.",
            1 if oldest and oldest < 2000 else 0,
            1,
        ),
        badge("Time Traveller", "Review a paper in its year of publication.", len(same_year), 1),
        badge("Hat Trick", "Three papers inside one week.", busiest, 3),
        badge("Marathon", "A four-week reading streak.", stats["streak"]["best"], 4, " weeks"),
        badge("Iron Reader", "A twelve-week reading streak.", stats["streak"]["best"], 12, " weeks"),
        badge("Polymath", "Papers spanning eight different topics.", len(topics), 8),
        badge("Desk Rejector", "Reject five papers.", stats["rejected"], 5),
        badge("Nitpicker", "Write a 1500-word review.", longest, 1500, " words"),
        badge("Connected", "Link one paper to three others.", most_related, 3),
        badge("Completionist", "Clear an entire tag off the backlog.", len(swept), 1),
        badge(
            "Full Slate",
            f"Hit the annual target of {stats['year']['target']}.",
            stats["year"]["read"],
            stats["year"]["target"],
        ),
    ]


# --------------------------------------------------------------------------- outputs


# Every review has the same shape: Review (the verdict), Problem (what's being solved),
# Overview (the tutorial in my own words), then optional Additional thoughts / Feedback.
REQUIRED_SECTIONS = ("Review", "Problem", "Overview")
PLACEHOLDER = "haven't written"


def lint(papers) -> list[str]:
    """Nag about reviews that don't follow the house structure. Warnings only — an unfinished
    review still counts, it just shouldn't be quietly unfinished."""
    warnings = []
    for p in sorted(papers, key=lambda p: p["slug"]):
        missing = ", ".join(f"## {s}" for s in REQUIRED_SECTIONS if s not in p["sections"])
        if missing:
            warnings.append(f"{p['slug']}: missing {missing}")
        if PLACEHOLDER in p["body"]:
            warnings.append(f"{p['slug']}: the Review section is still a placeholder")
        # Drafts are skipped entirely, so this only fires once a mined draft is published —
        # which is exactly when quoting a private conversation starts to matter.
        if "MINED EVIDENCE" in p["body"]:
            warnings.append(f"{p['slug']}: mined evidence block still present — scrub it")
        if p.get("rating") is None:
            warnings.append(f"{p['slug']}: no rating yet — still under review")
        if p.get("depth") == "rebuilt" and not p.get("notebooks"):
            warnings.append(f"{p['slug']}: depth is 'rebuilt' but no notebooks are listed")
    return warnings


def render_stats(stats: dict) -> str:
    body = yaml.safe_dump(stats, sort_keys=False, allow_unicode=True, width=100)
    return f"{STAMP}\n# Run it after adding or editing a paper; CI checks that it is current.\n\n{body}"


def tag_stub(tag: dict) -> str:
    return (
        "---\n"
        "layout: tag\n"
        f"title: {tag['label']}\n"
        f"tag: {tag['slug']}\n"
        f"kind: {tag['kind']}\n"
        f"permalink: /papers/tag/{tag['slug']}/\n"
        "---\n"
    )


def write_tag_pages(stats: dict) -> list[Path]:
    TAGS_DIR.mkdir(exist_ok=True)
    wanted = {}
    for tag in stats["by_tag"]:
        wanted[tag["slug"]] = tag_stub(tag)
    for stale in TAGS_DIR.glob("*.md"):
        if stale.name[:-3] not in wanted:
            stale.unlink()
    written = []
    for slug, content in wanted.items():
        path = TAGS_DIR / f"{slug}.md"
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def summarise(stats: dict) -> str:
    rank, nxt = stats["rank"], stats["next_rank"]
    lines = [
        f"  {stats['papers']} papers · {stats['xp']} XP · {rank['name']}",
    ]
    if nxt:
        lines.append(f"  {nxt['remaining']} XP to {nxt['name']} ({nxt['pct']}%)")
    year = stats["year"]
    pace = "ahead of pace" if year["ahead_by"] >= 0 else "behind pace"
    weeks = stats["streak"]["current"]
    lines += [
        f"  {year['read']}/{year['target']} in {year['value']} "
        f"({abs(year['ahead_by'])} {pace})",
        f"  streak {weeks} week{'' if weeks == 1 else 's'} (best {stats['streak']['best']})",
        f"  accepted {stats['accepted']} · rejected {stats['rejected']} "
        f"· under review {stats['under_review']}",
        f"  backlog {stats['backlog']['cleared']}/{stats['backlog']['total']} cleared "
        f"({stats['backlog']['pct']}%), {stats['backlog']['starred_open']} starred still open",
    ]
    earned = [b for b in stats["badges"] if b["earned"]]
    lines.append(f"  badges {len(earned)}/{len(stats['badges'])}: " + ", ".join(b["name"] for b in earned))
    nearly = [b for b in stats["badges"] if not b["earned"]][:3]
    if nearly:
        lines.append("  next up: " + ", ".join(f"{b['name']} ({b['detail']})" for b in nearly))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed stats are stale instead of rewriting them",
    )
    parser.add_argument("--today", help="override today's date (YYYY-MM-DD), for testing")
    args = parser.parse_args()

    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    gamify = yaml.safe_load((DATA / "gamify.yml").read_text(encoding="utf-8"))
    tags_cfg = yaml.safe_load((DATA / "tags.yml").read_text(encoding="utf-8")) or {}
    backlog = yaml.safe_load((DATA / "backlog.yml").read_text(encoding="utf-8")) or []

    papers = load_papers()
    stats = score(papers, gamify, tags_cfg, backlog, today)
    rendered = render_stats(stats)
    target = DATA / "stats.yml"

    if args.check:
        existing = target.read_text(encoding="utf-8") if target.exists() else ""
        if existing != rendered:
            print("_data/stats.yml is stale — run `python scripts/score.py`", file=sys.stderr)
            return 1
        print("scoreboard is current")
        return 0

    target.write_text(rendered, encoding="utf-8")
    write_tag_pages(stats)
    print(summarise(stats))

    warnings = lint(papers)
    if warnings:
        print("\n  unfinished business:")
        for w in warnings:
            print(f"    {w}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
