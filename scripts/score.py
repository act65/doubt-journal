# The old single-file shape. These now live on part pages (tutorial.md, discussion.md,
# thoughts.md); finding one in index.md means a review that hasn't been moved over.
LEGACY_SECTIONS = ("Review", "Problem", "Overview", "Additional thoughts", "Feedback")


def lint(papers, rubric) -> list[str]:
    """Nag about reviews that don't follow the house structure. Warnings only — an unfinished
    review still counts, it just shouldn't be quietly unfinished."""
    warnings = []
    axes = rubric.get("axes") or []
    known = {a["key"] for a in axes}
    scale = rubric.get("scale") or {}
    lo, hi = scale.get("min", 1), scale.get("max", 4)
    top = (rubric.get("confidence") or {}).get("max", 5)

    for p in sorted(papers, key=lambda p: p["slug"]):
        slug = p["slug"]
        missing = missing_core(p, rubric)
        if missing:
            warnings.append(f"{slug}: under review until it has {', '.join(missing)}")
        legacy = [s for s in LEGACY_SECTIONS if s in p["sections"]]
        if legacy:
            warnings.append(f"{slug}: index.md still has " + ", ".join(f"## {s}" for s in legacy)
                            + " — those belong on the part pages")
        warnings += [f"{slug}: {e}" for e in p["part_errors"]]
        if "rating" in p.get("_written", ()):
            warnings.append(f"{slug}: `rating:` is computed from the axis scores — remove it")
        if p.get("confidence") is None:
            warnings.append(f"{slug}: no confidence yet")
        elif not (isinstance(p["confidence"], int) and 1 <= p["confidence"] <= top):
            warnings.append(f"{slug}: confidence should be a whole number 1–{top}")
        if not journal.answered(p.get("takeaways")):
            warnings.append(f"{slug}: no takeaways yet")
        review = p.get("review") or {}
        stray = sorted(set(review) - known)
        if stray:
            warnings.append(f"{slug}: review.{', review.'.join(stray)} — no such axis in "
                            f"_data/rubric.yml, so it isn't shown or scored")
        for axis in axes:
            entry = review.get(axis["key"]) or {}
            score = entry.get("score")
            if score is not None and journal.axis_score(p, axis, rubric) is None:
                warnings.append(f"{slug}: review.{axis['key']}.score should be a whole number "
                                f"{lo}–{hi}")
            table = axis.get("table")
            for column in (table or {}).get("columns") or []:
                if not column.get("values"):
                    continue
                for row in entry.get(table["key"]) or []:
                    value = journal.cell((row or {}).get(column["key"]))
                    if value is not None and value not in column["values"]:
                        warnings.append(f"{slug}: review.{axis['key']}.{table['key']} has "
                                        f"{column['key']}: {value!r} — expected one of "
                                        f"{', '.join(column['values'])}")
        # Drafts are skipped entirely, so this only fires once a mined draft is published —
        # which is exactly when quoting a private conversation starts to matter.
        if "MINED EVIDENCE" in p["body"]:
            warnings.append(f"{slug}: mined evidence block still present — scrub it")
        if p.get("depth") == "rebuilt" and not p.get("notebooks"):
            warnings.append(f"{slug}: depth is 'rebuilt' but no notebooks are listed")
    return warnings


def render_stats(stats: dict) -> str:
    body = yaml.safe_dump(stats, sort_keys=False, allow_unicode=True, width=100)
    return f"{STAMP}\n# Run it after adding or editing a paper; CI rescores at build time.\n\n{body}"


def tag_stub(tag: dict) -> str:
    return (
        "---\n"
        "layout: tag\n"
        f"title: {tag['label']}\n"
        f"tag: {tag['slug']}\n"
        f"kind: {tag['kind']}\n"
        f"permalink: /papers/tag/{tag['slug']}/\n"
        "---\n"
    )


def write_tag_pages(stats: dict) -> list[Path]:
    TAGS_DIR.mkdir(exist_ok=True)
    wanted = {}
    for tag in stats["by_tag"]:
        wanted[tag["slug"]] = tag_stub(tag)
    for stale in TAGS_DIR.glob("*.md"):
        if stale.name[:-3] not in wanted:
            stale.unlink()
    written = []
    for slug, content in wanted.items():
        path = TAGS_DIR / f"{slug}.md"
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def summarise(stats: dict) -> str:
    rank, nxt = stats["rank"], stats["next_rank"]
    lines = [
        f"  {stats['papers']} papers · {stats['xp']} XP · {rank['name']}",
    ]
    idle = stats["idle"]
    if idle:
        if idle["missed"]:
            lines.append(
                f"  -{idle['xp_lost']} XP for {len(idle['missed'])} idle "
                f"week{'' if len(idle['missed']) == 1 else 's'} (earned {stats['xp_earned']})"
            )
        if not idle["this_week_safe"]:
            lines.append(
                f"  nothing read in {idle['this_week']} yet — finish a paper by "
                f"{idle['deadline']} or lose {idle['xp_each']} XP"
            )
    due = stats["due"]
    if due["xp_lost"]:
        lines.append(
            f"  -{due['xp_lost']} XP for {len(due['overdue'])} overdue "
            f"review{'' if len(due['overdue']) == 1 else 's'}"
        )
    for late in due["overdue"]:
        lines.append(f"    {late['slug']}: due {late['due']}, {late['days_late']} days late "
                     f"(-{late['xp']} XP)")
    if due["next"]:
        nxt_due = due["next"]
        lines.append(f"  next deadline: {nxt_due['slug']} in {nxt_due['days_left']} days "
                     f"({nxt_due['due']})")
    if nxt:
        lines.append(f"  {nxt['remaining']} XP to {nxt['name']} ({nxt['pct']}%)")
    year = stats["year"]
    pace = "ahead of pace" if year["ahead_by"] >= 0 else "behind pace"
    weeks = stats["streak"]["current"]
    lines += [
        f"  {year['read']}/{year['target']} in {year['value']} "
        f"({abs(year['ahead_by'])} {pace})",
        f"  streak {weeks} week{'' if weeks == 1 else 's'} (best {stats['streak']['best']})",
        f"  reviewed {stats['reviewed']} · under review {stats['under_review']}",
        f"  queue {stats['queue']['open']} open "
        f"({stats['queue']['curated_open']} curated, {stats['queue']['in_progress']} half-written)",
    ]
    earned = [b for b in stats["badges"] if b["earned"]]
    lines.append(f"  badges {len(earned)}/{len(stats['badges'])}: " + ", ".join(b["name"] for b in earned))
    nearly = [b for b in stats["badges"] if not b["earned"]][:3]
    if nearly:
        lines.append("  next up: " + ", ".join(f"{b['name']} ({b['detail']})" for b in nearly))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed stats are stale instead of rewriting them",
    )
    parser.add_argument("--today", help="override today's date (YYYY-MM-DD), for testing")
    args = parser.parse_args()

    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    gamify = yaml.safe_load((DATA / "gamify.yml").read_text(encoding="utf-8"))
    tags_cfg = yaml.safe_load((DATA / "tags.yml").read_text(encoding="utf-8")) or {}
    parts_cfg = yaml.safe_load((DATA / "parts.yml").read_text(encoding="utf-8")) or []
    rubric = journal.load_rubric()
    queue = journal.load_queue()

    papers = load_papers(parts_cfg, rubric)
    stats = score(papers, gamify, tags_cfg, rubric, queue, today)
    rendered = render_stats(stats)
    target = DATA / "stats.yml"

    if args.check:
        existing = target.read_text(encoding="utf-8") if target.exists() else ""
        if existing != rendered:
            print("_data/stats.yml is stale — run `python scripts/score.py`", file=sys.stderr)
            return 1
        print("scoreboard is current")
        return 0

    target.write_text(rendered, encoding="utf-8")
    write_tag_pages(stats)
    print(summarise(stats))

    warnings = lint(papers, rubric)
    if warnings:
        print("\n  unfinished business:")
        for w in warnings:
            print(f"    {w}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
