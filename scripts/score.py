def paper_badges(paper, rubric, low, status) -> list[dict]:
    """The PAPER_BADGES a finished review has earned. Unfinished reviews earn nothing — a badge
    on half-scored axes would be a verdict before there is one."""
    if status == "under-review":
        return []
    axes = rubric.get("axes") or []
    by_key = {a["key"]: a for a in axes}
    score = {a["key"]: journal.axis_score(paper, a, rubric) for a in axes}
    values = [v for v in score.values() if v is not None]
    lo, hi = (rubric.get("scale") or {}).get("min", 1), (rubric.get("scale") or {}).get("max", 4)
    rating, confidence = paper.get("rating"), paper.get("confidence")

    def axis(key):  # None if the rubric has no such axis
        return score.get(key)

    def column(axis_key, col):
        a = by_key.get(axis_key)
        return [journal.cell(row.get(col)) for row in journal.table_rows(paper, a)] if a else []

    holds = column("rigour", "holds")
    checked = [h for h in holds if h != "unverified"]
    stated = column("scope", "stated")
    rules = {
        "best-paper": values and all(v == hi for v in values),
        "required-reading": rating is not None and rating >= 8 and axis("clarity") == hi,
        "airtight": axis("rigour") == hi and holds and all(h == "yes" for h in holds),
        "solid": values and all(v == 3 for v in values),
        "hidden-gem": rating is not None and rating < low and axis("contribution") == hi,
        "diamond-rough": axis("contribution") == hi and (axis("clarity") or hi) <= 2,
        "well-told": axis("clarity") == hi and (axis("contribution") or hi) <= 2,
        "jekyll-hyde": hi in values and lo in values,
        "beautiful-conjecture": axis("idea") == hi and (axis("rigour") or hi) <= 2,
        "right-question": axis("why") == hi and (axis("idea") or hi) <= 2,
        "solution-seeking": (axis("idea") or 0) >= 3 and (axis("why") or hi) <= 2,
        # `partly` is half a hold, so one partly-held claim on its own isn't an overclaim.
        "overclaimed": checked and sum({"yes": 1, "partly": 0.5}.get(h, 0) for h in checked)
                       < len(checked) / 2,
        "taken-on-faith": holds and (len(holds) - len(checked)) > len(holds) / 2,
        "fine-print": stated and stated.count("no") > stated.count("yes"),
        "fatal-flaw": lo in values,
        "hot-take": rating is not None and confidence is not None and confidence <= 2
                    and (rating >= 8 or rating <= 2),
    }
    return [b for b in PAPER_BADGES if rules.get(b["key"])]


def award(papers, stats, gamify, tags_cfg, xp_of, status_of, low) -> list[dict]:
    """Rule-based badges. Each returns (earned, detail) where detail shows progress."""
    depth_cfg = gamify.get("depth") or {}
    deep = [p for p in papers if p.get("depth") in ("rebuilt", "extended")]
    weeks = Counter(iso_week(p["read_date"]) for p in papers if p["read_date"])
    topics = {
        t
        for p in papers
        for t in p["tags"]
        if (tags_cfg.get(t) or {}).get("kind") == "topic"
    }
    same_year = [p for p in papers if p["read_date"] and p.get("year") == p["read_date"].year]
    longest = max((p["words"] for p in papers), default=0)
    most_related = max((len(p["related"]) for p in papers), default=0)
    busiest = max(weeks.values(), default=0)
    # A topic is swept once you have read something in it and the queue holds nothing else.
    # Topics only: `disputed` and the other meta tags are never in the queue, so counting
    # them would hand this out for free.
    open_tags = set(stats["queue"]["tags_open"])
    swept = [t for t in topics if t not in open_tags]
    oldest = min((p["year"] for p in papers if p.get("year")), default=None)

    def badge(name, blurb, have, need, unit=""):
        return {
            "name": name,
            "blurb": blurb,
            "earned": have >= need,
            "detail": f"{min(have, need)} / {need}{unit}",
        }

    return [
        badge("First Blood", "Review one paper.", len(papers), 1),
        badge("Reproducer", "Rebuild five papers from scratch.", len(deep), 5),
        badge(
            "Deep Diver",
            "Take one paper further than its authors did.",
            sum(1 for p in papers if p.get("depth") == "extended"),
            1,
        ),
        badge(
            "Archivist",
            "Review something published before 2000.",
            1 if oldest and oldest < 2000 else 0,
            1,
        ),
        badge("Time Traveller", "Review a paper in its year of publication.", len(same_year), 1),
        badge("Hat Trick", "Three papers inside one week.", busiest, 3),
        badge("Marathon", "A four-week reading streak.", stats["streak"]["best"], 4, " weeks"),
        badge("Iron Reader", "A twelve-week reading streak.", stats["streak"]["best"], 12, " weeks"),
        badge("Polymath", "Papers spanning eight different topics.", len(topics), 8),
        badge("Nitpicker", "Write a 1500-word review.", longest, 1500, " words"),
        badge("Connected", "Link one paper to three others.", most_related, 3),
        badge("Completionist", "Read a tag dry — nothing left in the queue.", len(swept), 1),
        badge(
            "Full Slate",
            f"Hit the annual target of {stats['year']['target']}.",
            stats["year"]["read"],
            stats["year"]["target"],
        ),
    ]


