# --------------------------------------------------------------------------- loading


def load_papers(parts_cfg: list[dict], rubric: dict) -> list[dict]:
    papers = []
    for index in sorted(PAPERS.glob("*/index.md")):
        fm, body = read_front_matter(index)
        # Drafts are scaffolding: excluded from the scoreboard, and `published: false` keeps
        # Jekyll from rendering them too. Neither counts until you say it does.
        if fm.get("draft") or fm.get("published") is False:
            continue
        fm["slug"] = index.parent.name
        # Never hand-written: the rating is arithmetic on the rubric's axis scores.
        fm["_written"] = set(fm)
        fm["rating"] = compute_rating(fm, rubric)
        fm["read_date"] = as_date(fm.get("read"))
        # The part pages are the same review, just on separate URLs, so they count toward its
        # length. notes.md is private scratch and doesn't.
        fm["parts"], fm["part_errors"], bodies = [], [], [body]
        for part in parts_cfg:
            path = index.parent / f"{part['key']}.md"
            if not path.exists():
                continue
            part_fm, part_body = read_front_matter(path)
            if part_fm.get("part") != part["key"] or part_fm.get("slug") != index.parent.name:
                fm["part_errors"].append(f"{path.name} needs `part: {part['key']}` and "
                                         f"`slug: {index.parent.name}`")
            fm["parts"].append(part["key"])
            bodies.append(part_body)
        fm["words"] = sum(len(b.split()) for b in bodies)
        fm["sections"] = re.findall(r"^##\s+(.+?)\s*$", body, re.M)
        fm["body"] = body
        fm["tags"] = fm.get("tags") or []
        fm["notebooks"] = fm.get("notebooks") or []
        fm["related"] = fm.get("related") or []
        papers.append(fm)
    return papers


# --------------------------------------------------------------------------- helpers


def iso_week(date: dt.date) -> str:
    year, week, _ = date.isocalendar()
    return f"{year}-W{week:02d}"


def week_start(date: dt.date) -> dt.date:
    return date - dt.timedelta(days=date.isoweekday() - 1)


def tag_meta(slug: str, tags_cfg: dict) -> dict:
    meta = tags_cfg.get(slug) or {}
    return {
        "slug": slug,
        "label": meta.get("label") or slug.replace("-", " ").capitalize(),
        "kind": meta.get("kind") or "other",
    }


# --------------------------------------------------------------------------- scoring


def score(papers, gamify, tags_cfg, rubric, queue, today: dt.date) -> dict:
    depth_cfg = gamify.get("depth") or {}
    # There is no accepted/rejected: the rating is the verdict. `low_rating` only says what
    # counts as low for Hidden Gem.
    low = gamify.get("low_rating", 5)

    def xp_of(paper) -> int:
        return int((depth_cfg.get(paper.get("depth")) or {}).get("xp", 0))

    def status_of(paper) -> str:
        # Scores with no reasons behind them are still under review — the rating waits for the
        # whole core (journal.missing_core), the same rule the queue and the deadlines use.
        return "reviewed" if is_finished(paper, rubric) else "under-review"

    earned_xp = sum(xp_of(p) for p in papers)
    read_weeks = {iso_week(p["read_date"]) for p in papers if p["read_date"]}
    idle = idle_weeks(read_weeks, gamify.get("idle_penalty") or {}, today)
    due = overdue(queue, gamify.get("review_deadline") or {}, today)
    total_xp = max(0, earned_xp - (idle["xp_lost"] if idle else 0) - due["xp_lost"])

    # Rank: the highest threshold we have passed, and how far to the next one.
    ranks = sorted(gamify.get("ranks") or [], key=lambda r: r["at"])
    current = ranks[0] if ranks else {"at": 0, "name": "Unranked"}
    following = None
    for rank in ranks:
        if total_xp >= rank["at"]:
            current = rank
        else:
            following = rank
            break
    if following:
        span = following["at"] - current["at"]
        pct = round(100 * (total_xp - current["at"]) / span) if span else 100
        next_rank = {
            "name": following["name"],
            "at": following["at"],
            "remaining": following["at"] - total_xp,
            "pct": pct,
        }
    else:
        next_rank = None

    statuses = Counter(status_of(p) for p in papers)

    by_depth = []
    for slug, cfg in depth_cfg.items():
        matching = [p for p in papers if p.get("depth") == slug]
        by_depth.append(
            {
                "slug": slug,
                "label": cfg.get("label", slug),
                "xp_each": cfg.get("xp", 0),
                "count": len(matching),
                "xp": sum(xp_of(p) for p in matching),
            }
        )

    # Only finished reviews are listed on the site, so only they are counted.
    tag_counts = Counter(t for p in papers if status_of(p) == "reviewed" for t in p["tags"])
    by_tag = sorted(
        ({**tag_meta(slug, tags_cfg), "count": n} for slug, n in tag_counts.items()),
        key=lambda t: (-t["count"], t["slug"]),
    )

    by_year = [
        {"year": year, "count": n}
        for year, n in sorted(Counter(p["year"] for p in papers if p.get("year")).items())
    ]
    ratings = [
        {"rating": r, "count": n}
        # Computed ratings have a decimal; the histogram buckets them to whole points.
        for r, n in sorted(Counter(round(p["rating"]) for p in papers if status_of(p) == "reviewed").items())
    ]

    # ---- streaks, measured in ISO weeks with at least one paper finished
    read_dates = [p["read_date"] for p in papers if p["read_date"]]
    weeks = Counter(iso_week(d) for d in read_dates)

    this_week = week_start(today)
    # One week of grace: finishing nothing yet this week does not kill a live streak.
    cursor = this_week if iso_week(this_week) in weeks else this_week - dt.timedelta(days=7)
    streak = 0
    while iso_week(cursor) in weeks:
        streak += 1
        cursor -= dt.timedelta(days=7)

    best, run, previous = 0, 0, None
    for start in sorted({week_start(d) for d in read_dates}):
        run = run + 1 if previous and (start - previous).days == 7 else 1
        best, previous = max(best, run), start

    recent = []
    for i in range(25, -1, -1):
        start = this_week - dt.timedelta(days=7 * i)
        recent.append({"week": iso_week(start), "count": weeks.get(iso_week(start), 0)})

    # ---- annual target
    target = gamify.get("annual_target", 52)
    this_year = sum(1 for d in read_dates if d.year == today.year)
    elapsed = (today - dt.date(today.year, 1, 1)).days + 1
    days_in_year = (dt.date(today.year, 12, 31) - dt.date(today.year, 1, 1)).days + 1
    expected = target * elapsed / days_in_year
    year_stats = {
        "value": today.year,
        "read": this_year,
        "target": target,
        "pct": round(100 * this_year / target) if target else 0,
        "expected_by_now": round(expected, 1),
        "ahead_by": round(this_year - expected, 1),
    }

    # ---- the reading queue
    #
    # The queue prunes itself: a paper leaves _data/queue.yml once its review is finished
    # (journal.is_finished), and a skipped paper leaves after its second strike. So there is no
    # "cleared" fraction to report any more — what matters is the shape of what's left, and
    # how much of it you put there on purpose.
    open_entries = [e for e in queue if not e.get("taken")]
    queue_tags = Counter(t for e in open_entries for t in (e.get("tags") or []))
    queue_stats = {
        "total": len(queue),
        "open": len(open_entries),
        "taken": len(queue) - len(open_entries),
        "curated_open": sum(1 for e in open_entries if e.get("curated")),
        "starred_open": sum(1 for e in open_entries if e.get("starred")),
        "in_progress": sum(1 for e in open_entries if e.get("slug")),
        "struck": sum(1 for e in open_entries if e.get("strikes")),
        "no_link": sum(1 for e in open_entries if not e.get("url")),
        "by_source": [
            {"source": s, "count": n}
            for s, n in sorted(Counter(e.get("source", "?") for e in open_entries).items())
        ],
        # by_tag is the headline dozen; tags_open is every tag still represented, which is
        # what the Completionist badge counts against.
        "by_tag": sorted(
            ({**tag_meta(slug, tags_cfg), "count": n} for slug, n in queue_tags.items()),
            key=lambda t: (-t["count"], t["slug"]),
        )[:12],
        "tags_open": sorted(queue_tags),
    }

    # Per-paper verdicts, so the templates never have to decide what "finished" means.
    reviews = {
        p["slug"]: {
            "status": status_of(p),
            "rating": p["rating"],
            "badges": [b["key"] for b in paper_badges(p, rubric, low, status_of(p))],
            "missing": missing_core(p, rubric),
            "parts": p["parts"],
        }
        for p in papers
    }

    stats = {
        "papers": len(papers),
        "xp": total_xp,
        "xp_earned": earned_xp,
        "idle": idle,
        "rank": {"name": current.get("name"), "at": current.get("at", 0)},
        "next_rank": next_rank,
        "reviewed": statuses["reviewed"],
        "under_review": statuses["under-review"],
        # The finished reviews, rating first: what /papers/ and the tag pages list.
        "listed": [p["slug"] for p in sorted(
            (p for p in papers if status_of(p) == "reviewed"), key=lambda p: (-p["rating"], p["slug"]))],
        "by_depth": by_depth,
        "by_tag": by_tag,
        "by_year": by_year,
        "ratings": ratings,
        "year": year_stats,
        "streak": {"current": streak, "best": best, "weeks": recent},
        "queue": queue_stats,
        "due": due,
        "reviews": reviews,
        # The catalogue, each with the papers that earned it — for /badges/.
        "paper_badges": [
            {**badge, "blurb": badge["blurb"].format(low=low),
             "papers": [slug for slug, r in reviews.items() if badge["key"] in r["badges"]]}
            for badge in PAPER_BADGES
        ],
    }
    stats["badges"] = award(papers, stats, gamify, tags_cfg, xp_of, status_of, low)
    return stats


def idle_weeks(read_weeks: set[str], cfg: dict, today: dt.date) -> dict | None:
    """Charge every finished week since ``cfg['since']`` that has no paper in it.

    The current week is only reported, never charged: it can still be saved before Sunday.
    """
    since = as_date(cfg.get("since"))
    if not since:
        return None
    each = int(cfg.get("xp", 1))
    this_week = week_start(today)
    missed, cursor = [], week_start(since)
    while cursor < this_week:
        if iso_week(cursor) not in read_weeks:
            missed.append(iso_week(cursor))
        cursor += dt.timedelta(days=7)
    return {
        "since": since.isoformat(),
        "xp_each": each,
        "missed": missed,
        "xp_lost": each * len(missed),
        "this_week": iso_week(this_week),
        "this_week_safe": iso_week(this_week) in read_weeks or this_week < week_start(since),
        "deadline": (this_week + dt.timedelta(days=6)).isoformat(),
    }


def overdue(queue, cfg: dict, today: dt.date) -> dict:
    """Charge for reviews accepted from the queue and not finished by their due date.

    `scripts/next_paper.py` writes `taken: {slug, on, due}` when a paper is accepted, and the
    debt is settled the moment that paper's review is finished (journal.is_finished) — at which point the
    entry leaves the queue entirely. Each finished week late costs `xp`, capped at `max_xp`
    per paper so one abandoned draft cannot zero the whole scoreboard.
    """
    days = int(cfg.get("days") or 14)
    each = int(cfg.get("xp") or 0)
    cap = cfg.get("max_xp")
    since = as_date(cfg.get("since"))
    status = journal.load_paper_status()

    late, upcoming = [], []
    for entry in queue:
        taken = entry.get("taken") or {}
        accepted, due_on = as_date(taken.get("on")), as_date(taken.get("due"))
        if not due_on:
            continue
        slug = taken.get("slug") or entry.get("slug")
        paper = status.get(slug) or {}
        if paper.get("finished"):
            continue
        if since and accepted and accepted < since:
            continue
        behind = (today - due_on).days
        if behind <= 0:
            upcoming.append(
                {"slug": slug, "title": entry.get("title"), "due": due_on.isoformat(),
                 "days_left": -behind}
            )
            continue
        weeks = behind // 7
        cost = each * weeks
        if cap is not None:
            cost = min(cost, int(cap))
        late.append(
            {
                "slug": slug,
                "title": entry.get("title"),
                "due": due_on.isoformat(),
                "days_late": behind,
                "weeks_late": weeks,
                "xp": cost,
            }
        )

    late.sort(key=lambda r: r["due"])
    upcoming.sort(key=lambda r: r["due"])
    return {
        "days": days,
        "xp_each": each,
        "max_xp": cap,
        "since": since.isoformat() if since else None,
        "accepted": len(late) + len(upcoming),
        "overdue": late,
        "xp_lost": sum(r["xp"] for r in late),
        "upcoming": upcoming,
        "next": upcoming[0] if upcoming else None,
    }


