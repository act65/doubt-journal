#!/usr/bin/env python3
"""Score the journal.

Reads every paper in ``_papers/*/index.md`` (and the part pages beside it — tutorial,
discussion, thoughts) plus the rules in ``_data/gamify.yml`` and writes
the derived scoreboard to ``_data/stats.yml``. Jekyll does no arithmetic — it just renders what
this script computed, so the numbers on the site are reproducible offline and land in git as a
diff you can read (``xp: 16 -> 24``).

    python scripts/score.py            # recompute, write, print the summary
    python scripts/score.py --check    # fail if _data/stats.yml is stale

Also regenerates the per-tag stub pages in ``tags/`` so every tag has a real URL, and
charges for any review accepted off the reading queue that is past its due date.
"""

from __future__ import annotations

