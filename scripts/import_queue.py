# --------------------------------------------------------------------------- BibTeX


LATEX = {
    r"\&": "&", r"\%": "%", r"\$": "$", r"\#": "#", r"\_": "_",
    r"{\textbackslash}": "\\", r"\textbackslash": "\\",
    r"{\textquotesingle}": "'", r"{\textendash}": "–", r"{\textemdash}": "—",
    r"{\textquotedblleft}": '"', r"{\textquotedblright}": '"',
    r"\textasciitilde": "~", r"~": " ",
}


def unlatex(value: str) -> str:
    """Flatten a BibTeX value to plain text: Zotero's {Brace}{Protection} and the escapes."""
    out = value
    for src, dst in LATEX.items():
        out = out.replace(src, dst)
    # Accents: {\'e} / {\"o} / \'{e} -> the bare letter. Good enough for a queue entry.
    out = re.sub(r"\{?\\[`'\"^~=.]\{?([a-zA-Z])\}?\}?", r"\1", out)
    out = re.sub(r"\\[a-zA-Z]+\s*", "", out)
    out = out.replace("{", "").replace("}", "")
    return re.sub(r"\s+", " ", out).strip()


def split_entries(text: str) -> list[tuple[str, str]]:
    """Yield (type, body) for every @entry, tracking braces so nested ones don't end it."""
    entries = []
    i = 0
    while True:
        at = text.find("@", i)
        if at < 0:
            return entries
        m = re.match(r"@(\w+)\s*\{", text[at:])
        if not m:
            i = at + 1
            continue
        start = at + m.end()
        depth, j = 1, start
        while j < len(text) and depth:
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
            j += 1
        entries.append((m.group(1).lower(), text[start : j - 1]))
        i = j


def parse_fields(body: str) -> dict[str, str]:
    """Pull `name = {value}` pairs out of one entry body, brace-aware."""
    fields: dict[str, str] = {}
    for m in re.finditer(r"(?:^|,)\s*([a-zA-Z-]+)\s*=\s*", body):
        name = m.group(1).lower()
        k = m.end()
        if k >= len(body):
            break
        if body[k] == "{":
            depth, j = 1, k + 1
            while j < len(body) and depth:
                if body[j] == "{":
                    depth += 1
                elif body[j] == "}":
                    depth -= 1
                j += 1
            fields[name] = body[k + 1 : j - 1]
        elif body[k] == '"':
            j = body.find('"', k + 1)
            fields[name] = body[k + 1 : j if j > 0 else len(body)]
        else:
            j = body.find(",", k)
            fields[name] = body[k : j if j > 0 else len(body)].strip()
    return fields


def surnames(author_field: str) -> str | None:
    """'Hermann, Jan and Spencer, James and ...' -> 'Hermann, Spencer & Choo' / 'X et al.'"""
    if not author_field:
        return None
    people = [a.strip() for a in re.split(r"\s+and\s+", unlatex(author_field)) if a.strip()]
    names = []
    for person in people:
        names.append(person.split(",")[0].strip() if "," in person else person.split()[-1])
    names = [n for n in names if n]
    if not names:
        return None
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f"{names[0]} & {names[1]}"
    if len(names) == 3:
        return f"{names[0]}, {names[1]} & {names[2]}"
    return f"{names[0]} et al."


ARXIV_IN_NOTE = re.compile(r"arxiv:\s*([0-9]{4}\.[0-9]{4,5}|[a-z-]+/[0-9]{7})", re.I)


def read_bib(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8", errors="replace")
    rows = []
    for _, body in split_entries(text):
        f = parse_fields(body)
        title = unlatex(f.get("title", ""))
        if not title:
            continue
        url = (f.get("url") or "").strip() or None
        if not url and f.get("doi"):
            url = "https://doi.org/" + unlatex(f["doi"])
        if not url:
            note = ARXIV_IN_NOTE.search(f.get("note", "") or "")
            if note:
                url = "https://arxiv.org/abs/" + note.group(1)
        keywords = unlatex(f.get("keywords", ""))
        year = None
        if f.get("year"):
            ym = re.search(r"\d{4}", f["year"])
            year = int(ym.group()) if ym else None
        # Zotero has no date-added in a BibTeX export. `urldate` (date accessed) is the
        # closest thing to "when did this land in my library"; failing that, assume the
        # paper was added the year it came out.
        added, added_est = as_date(f.get("urldate")), False
        if not added:
            added, added_est = (dt.date(year, 1, 1) if year else None), True
        rows.append(
            {
                "title": title,
                "url": url,
                "authors": surnames(f.get("author", "")),
                "year": year,
                "source": "zotero",
                "added": added,
                "added_est": added_est,
                "starred": "★" in keywords,
                "tags": guess_tags(title, keywords, unlatex(f.get("abstract", ""))),
            }
        )
    return rows


# --------------------------------------------------------------------------- Google Keep

URL_RE = re.compile(r"https?://[^\s<>)\]]+")
MD_LINK = re.compile(r"^\s*[-*]?\s*\[(?P<title>[^\]]+)\]\((?P<url>[^)]+)\)\s*$")

# The headers in the newest lists, mapped onto the journal's own topic tags.
KEEP_GROUP_TAGS = {
    "flows / work": ["flow-matching", "generative-models"],
    "uncertainty": ["uncertainty"],
    "rl": ["rl"],
    "governance": ["economics"],
    "general interest": [],
}

# Pages that index other papers rather than being one.
INDEX_URL = re.compile(r"icml\.cc/Conferences|proceedings\.mlr\.press/?$|AcceptedPapers", re.I)

# A block of this many bare title lines is a pasted list — one paper per line. Anything
# shorter is a single title that wrapped when it was copied out of a PDF.
LIST_BLOCK = 4


def read_keep(path: Path, today: dt.date) -> list[dict]:
    """Parse the Keep dump. The file is newest list first, which is the only record of when
    any of this was collected, so position in the file becomes the recency signal."""
    raw = path.read_text(encoding="utf-8", errors="replace")
    rows: list[dict] = []

    for block in re.split(r"\n\s*\n", raw):
        lines = [l.strip() for l in block.splitlines() if l.strip()]
        if not lines:
            continue
        group_tags: list[str] = []
        # A markdown-link block opens with its Keep heading.
        if not URL_RE.search(lines[0]) and any(MD_LINK.match(l) for l in lines[1:]):
            group_tags = KEEP_GROUP_TAGS.get(lines[0].lower(), [])
            lines = lines[1:]

        pending: list[str] = []
        bare_titles: list[str] = []
        for line in lines:
            md = MD_LINK.match(line)
            if md:
                rows.append(_keep_row(md.group("title"), md.group("url"), group_tags))
                continue
            stripped = re.sub(r"^\s*[-*]\s*", "", line)
            urls = URL_RE.findall(stripped)
            if urls:
                lead = URL_RE.sub("", stripped).strip(" \t-–—:")
                title = " ".join(pending + ([lead] if lead else [])).strip()
                pending = []
                row = _keep_row(title or None, urls[0].rstrip(".,);"), group_tags)
                # An index page is not a paper, but its URL still dates the lines around
                # it, so it rides along until the dating pass is done.
                row["_index"] = bool(INDEX_URL.search(urls[0]))
                rows.append(row)
                continue
            pending.append(stripped)
        # Whatever is left is title-only: either one wrapped title or a pasted list.
        if pending:
            if len(pending) >= LIST_BLOCK:
                bare_titles = pending
            else:
                bare_titles = [" ".join(pending)]
        for title in bare_titles:
            rows.append(_keep_row(title, None, group_tags))

    _date_keep(rows, today)
    return [r for r in rows if not r.pop("_index", False)]


def _keep_row(title: str | None, url: str | None, group_tags: list[str]) -> dict:
    title = re.sub(r"\s+", " ", title).strip() if title else None
    return {
        "title": title,
        "url": url,
        "authors": None,
        "year": None,
        "source": "keep",
        "added": None,
        "added_est": True,
        "starred": False,
        "tags": group_tags or guess_tags(title),
    }


ARXIV_ID = re.compile(r"arxiv\.org/(?:abs|pdf)/(\d{2})(\d{2})\.\d{4,5}", re.I)
# Conference URLs carry a year: proceedings.neurips.cc/paper/2021/..., iclr.cc/virtual/2025/...
URL_YEAR = re.compile(r"(?:neurips|iclr|icml|mlr\.press)[^\s]*?/(20[0-2]\d)(?:/|\b)", re.I)


def _lower_bound(url: str | None) -> dt.date | None:
    """Earliest date a link could possibly have been written down.

    An arXiv ID dates itself to the month; a conference URL to the year. Either way it is a
    *lower* bound on when the line was typed, never the date itself — an old paper can be
    noted down at any time.
    """
    if not url:
        return None
    m = ARXIV_ID.search(url)
    if m:
        yy, mm = int(m.group(1)), int(m.group(2))
        if 1 <= mm <= 12:
            return dt.date(2000 + yy, mm, 1)
    m = URL_YEAR.search(url)
    if m:
        return dt.date(int(m.group(1)), 1, 1)
    return None


FLOOR = dt.date(2019, 1, 1)


def _date_keep(rows: list[dict], today: dt.date) -> None:
    """Estimate when each Keep entry was collected, and fill `year` where the URL says it.

    The dump is ordered newest to oldest and carries no dates, so the only hard evidence is
    in the links: arXiv 2602.20070 cannot have been noted before February 2026, and a
    proceedings URL under /2021/ cannot have been noted before 2021. Each is a lower bound,
    and the newest-first ordering makes the estimates non-increasing down the file — so the
    tightest consistent estimate for a line is the latest bound appearing at or below it.
    """
    bounds = [_lower_bound(row["url"]) for row in rows]
    for row, bound in zip(rows, bounds):
        if bound and ARXIV_ID.search(row["url"] or ""):
            row["year"] = bound.year

    running = None
    for i in range(len(rows) - 1, -1, -1):
        if bounds[i] and (running is None or bounds[i] > running):
            running = bounds[i]
        rows[i]["added"] = min(running, today) if running else None

    # The tail is the ICML-2019 era and carries no links at all. Walk back up from the
    # oldest estimate towards a floor so those entries are at least ordered, not undated.
    undated = [i for i, row in enumerate(rows) if row["added"] is None]
    if undated:
        anchor = rows[max(undated) + 1]["added"] if max(undated) + 1 < len(rows) else FLOOR
        oldest = min(anchor or FLOOR, FLOOR)
        newest = rows[min(undated) - 1]["added"] if min(undated) > 0 else oldest
        span = max(len(undated) - 1, 1)
        drop = (newest - oldest).days
        for n, i in enumerate(undated):
            rows[i]["added"] = newest - dt.timedelta(days=round(drop * n / span))


