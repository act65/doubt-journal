def untag(fragment: str) -> str:
    """HTML fragment -> plain text."""
    text = re.sub(r"<[^>]+>", " ", fragment)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def unwrap_scholar(href: str) -> str | None:
    """Pull the real paper URL out of a scholar_url redirect."""
    query = urllib.parse.urlparse(html.unescape(href)).query
    target = urllib.parse.parse_qs(query).get("url", [None])[0]
    if not target:
        return None
    # Scholar sometimes double-encodes, and always appends its own tracking parameters.
    target = urllib.parse.unquote(target)
    cleaned = urllib.parse.urlsplit(target)
    keep = [
        (k, v)
        for k, v in urllib.parse.parse_qsl(cleaned.query)
        if k not in {"oi", "scisig", "sa", "hl", "d", "ct", "usg", "ei"}
    ]
    return urllib.parse.urlunsplit(cleaned._replace(query=urllib.parse.urlencode(keep)))


def header_text(message, name: str) -> str:
    raw = message.get(name)
    if not raw:
        return ""
    try:
        return str(make_header(decode_header(raw)))
    except (UnicodeDecodeError, LookupError, ValueError):
        return raw


def html_body(message) -> str:
    """The text/html part, decoded. Falls back to text/plain if that is all there is."""
    parts, fallback = [], []
    for part in message.walk() if message.is_multipart() else [message]:
        kind = (part.get_content_type() or "").lower()
        if kind not in ("text/html", "text/plain"):
            continue
        payload = part.get_payload(decode=True)
        if payload is None:
            continue
        charset = part.get_content_charset() or "utf-8"
        try:
            text = payload.decode(charset, "replace")
        except LookupError:
            text = payload.decode("utf-8", "replace")
        (parts if kind == "text/html" else fallback).append(text)
    return "\n".join(parts or fallback)


def parse_byline(line: str) -> tuple[str | None, int | None]:
    """'A Author, B Author - arXiv preprint arXiv:2602.20070, 2026' -> authors, year."""
    plain = untag(line)
    if not plain:
        return None, None
    people, _, venue = plain.partition(" - ")
    year = None
    years = re.findall(r"\b(19|20)\d{2}\b", venue or plain)
    if years:
        year = int(re.findall(r"\b((?:19|20)\d{2})\b", venue or plain)[-1])
    names = [n.strip() for n in people.split(",") if n.strip()]
    surname = [n.split()[-1] for n in names if n.split()]
    if not surname:
        authors = None
    elif len(surname) == 1:
        authors = surname[0]
    elif len(surname) == 2:
        authors = f"{surname[0]} & {surname[1]}"
    elif len(surname) == 3:
        authors = f"{surname[0]}, {surname[1]} & {surname[2]}"
    else:
        authors = f"{surname[0]} et al."
    return authors, year


def read_mbox(path: Path, all_senders: bool = False) -> list[dict]:
    """Every paper linked from a Google Scholar alert in a Gmail Takeout .mbox.

    Two things make this the best-behaved source in the queue. The `Date:` header is a real
    date, so `added` is not estimated for once; and the subject line carries the alert query
    you wrote yourself, which is better evidence of interest than guessing tags off a title.

    Starring is per-email, and one alert holds several papers — so a starred alert marks its
    papers `flagged`, meaning "one of these is the one you wanted", never `starred`. Which one
    is a judgement, and it stays yours.
    """
    rows: list[dict] = []
    for message in mailbox.mbox(str(path)):
        sender = header_text(message, "From").lower()
        if not all_senders and not any(s in sender for s in SCHOLAR_SENDERS):
            continue

        # Long label headers are folded across lines, so "Interesting papers" arrives as
        # "Interesting\n papers". Collapse the whitespace before splitting or it becomes two
        # labels, neither of which is the one the user made.
        raw_labels = re.sub(r"\s+", " ", header_text(message, "X-Gmail-Labels"))
        labels = [l.strip() for l in raw_labels.split(",") if l.strip()]
        if any(l.lower() in EXCLUDE_LABELS for l in labels):
            continue
        flagged = any(l.lower() == "starred" for l in labels)
        own_labels = [l for l in labels if l.lower() not in SYSTEM_LABELS
                      and not l.lower().startswith("category")]

        added = None
        if message.get("Date"):
            try:
                added = email.utils.parsedate_to_datetime(message["Date"]).date()
            except (TypeError, ValueError):
                added = None

        subject = re.sub(r"\s+", " ", header_text(message, "Subject")).strip()
        if NOT_AN_ALERT.match(subject):
            continue
        alert = subject
        for pattern in SUBJECT_QUERY:
            found = pattern.match(subject)
            if found:
                alert = found.group(1)
                break
        alert = alert.strip(' "\u201c\u201d') or None

        body = html_body(message)
        bylines = [m.group("line") for m in BYLINE.finditer(body)]

        anchors = list(SCHOLAR_LINK.finditer(body))
        titled = [m for m in anchors if TITLE_CLASS in (m.group("attrs") or "")]
        # Prefer Scholar's own title class; fall back to any redirect that reads like a title,
        # so a markup change degrades instead of returning nothing.
        chosen = titled or [
            m for m in anchors
            if not NOT_A_TITLE.match(untag(m.group("text")))
            and len(untag(m.group("text"))) > 12
        ]

        seen_here: set[str] = set()
        here: list[dict] = []
        for i, match in enumerate(chosen):
            title = untag(match.group("text"))
            url = unwrap_scholar(match.group("href"))
            if not title or (url and url in seen_here):
                continue
            if url:
                seen_here.add(url)
            authors, year = parse_byline(bylines[i]) if i < len(bylines) else (None, None)
            here.append(
                {
                    "title": title,
                    "url": url,
                    "authors": authors,
                    "year": year,
                    "source": "scholar",
                    "added": added,
                    "added_est": False,
                    "starred": False,
                    "flagged": False,
                    "alert": alert,
                    "labels": own_labels,
                    # The alert name is an author far more often than a subject, so the
                    # tags come off the title alone.
                    "tags": guess_tags(title),
                }
            )

        # What the star on this email actually picked out. If the alert held exactly one
        # paper there is no ambiguity — the star is about that paper, so it gets the real
        # thing. Otherwise the star is spread across the k papers it arrived with, and
        # `siblings` records k so the weight can be divided instead of guessed at.
        if flagged and here:
            for row in here:
                if len(here) == 1:
                    row["starred"] = True
                else:
                    row["flagged"] = True
                    row["siblings"] = len(here)
        rows.extend(here)
    return rows


# --------------------------------------------------------------------------- the repo itself


def read_papers() -> tuple[list[dict], list[dict]]:
    """Split _papers/ into (unfinished, finished).

    Finished means what the scoreboard means — journal.is_finished: published, with the
    core review written. Those are done. Everything else — a mined draft, a review with axes
    still unscored or unanswered — is a paper still owed, folder and all, so
    it goes back in the draw.
    """
    unfinished, finished = [], []
    rubric = journal.load_rubric()
    for index in sorted(PAPERS.glob("*/index.md")):
        fm, _ = journal.read_front_matter(index)
        slug = index.parent.name
        row = {
            "title": fm.get("title") or slug,
            "url": fm.get("ref") or None,
            "authors": fm.get("authors") or None,
            "year": fm.get("year") or None,
            "source": "papers",
            "added": as_date(fm.get("read")),
            "added_est": False,
            "starred": False,
            "tags": [t for t in (fm.get("tags") or [])],
            "slug": slug,
        }
        (finished if journal.is_finished(fm, rubric) else unfinished).append(row)
    return unfinished, finished


def read_existing(entries: list[dict]) -> list[dict]:
    """The queue as it stands, as just another source — and the authoritative one.

    This is what makes `python scripts/import_queue.py` safe to run with no arguments: the
    papers already in the queue come back in ahead of the exports, so a run without --bib
    refreshes the repo's own folders without throwing away two thousand Zotero entries.
    """
    rows = []
    for entry in entries:
        row = dict(entry)
        # clean() leaves falsy fields out of the file, so put the full shape back.
        row["title"] = entry.get("title")
        row["url"] = entry.get("url")
        row["authors"] = entry.get("authors")
        row["year"] = entry.get("year")
        row["added"] = as_date(entry.get("added"))
        row["added_est"] = bool(entry.get("added_est"))
        row["tags"] = list(entry.get("tags") or [])
        row["source"] = entry.get("source") or "queue"
        row["starred"] = bool(entry.get("starred"))
        row["flagged"] = bool(entry.get("flagged"))
        row["siblings"] = entry.get("siblings")
        row["labels"] = list(entry.get("labels") or [])
        rows.append(row)
    return rows


def read_backlog() -> list[dict]:
    """The old hand-curated shortlist, if a checkout still has one.

    _data/backlog.yml was folded into the queue (its entries are the ones carrying
    `curated: true`) and deleted. This reader stays so an older branch or a stashed copy
    imports cleanly rather than silently losing the only curated entries in the file.
    """
    if not BACKLOG.exists():
        return []
    rows = []
    for entry in yaml.safe_load(BACKLOG.read_text(encoding="utf-8")) or []:
        tag = entry.get("tag")
        rows.append(
            {
                "title": entry.get("title"),
                "url": entry.get("url") or None,
                "authors": entry.get("authors") or None,
                "year": entry.get("year") or None,
                "source": "backlog",
                # The backlog is not dated either. It was curated most recently of the
                # written-down sources, so it is treated as current.
                "added": None,
                "added_est": True,
                "starred": bool(entry.get("starred")),
                "curated": True,
                "tags": [tag] if tag and tag != "other" else guess_tags(entry.get("title")),
            }
        )
    return rows


# --------------------------------------------------------------------------- what isn't a paper

# Things a Scholar alert will happily hand you that cannot be reviewed as papers. Patents and
# meeting abstracts are the bulk of it; the rest are blog mirrors and scraper sites.
JUNK_DOMAINS = {
    # patents
    "patents.google.com", "freepatentsonline.com", "patentimages.storage.googleapis.com",
    "worldwide.espacenet.com", "patft.uspto.gov", "patents.justia.com",
    # conference abstracts, not papers
    "meetings.aps.org",
    # blogs, scrapers and translation mirrors
    "blog.csdn.net", "csdn.net", "russianblogs.com", "jove.com", "zhuanlan.zhihu.com",
    "programmersought.com", "chowdera.com", "slideshare.net",
}
PATENT_PATH = re.compile(r"/patent[s]?/", re.I)

# Scholar's "related research" alerts pick up translated pages. A title that is mostly
# non-Latin script is one of those, not something this journal is going to review.
NON_LATIN_SHARE = 0.3


def mostly_non_latin(title: str | None) -> bool:
    letters = [c for c in (title or "") if c.isalpha()]
    if not letters:
        return False
    # 0x2bf is past the Latin blocks and their diacritics, so accented titles stay.
    return sum(1 for c in letters if ord(c) > 0x2BF) / len(letters) > NON_LATIN_SHARE


def not_a_paper(row: dict) -> str | None:
    """Why this entry can't be reviewed, or None if it can. Applied to every source."""
    url = row.get("url") or ""
    host = urllib.parse.urlsplit(url).netloc.lower().removeprefix("www.") if url else ""
    if host in JUNK_DOMAINS:
        return host
    if PATENT_PATH.search(urllib.parse.urlsplit(url).path or ""):
        return "patent"
    if mostly_non_latin(row.get("title")):
        return "non-latin title"
    return None


# --------------------------------------------------------------------------- merge


KEEP_FIELDS = ("strikes", "taken", "slug", "weight", "alias", "unresolved", "starred")


def merge(sources, finished: list[dict], existing: list[dict], dropped, today: dt.date):
    """Fold every source into one list, best-known record first.

    Sources arrive most-considered first, so the first time a paper is seen wins its title and
    metadata; later sightings only contribute tags, stars and the earliest `added` date.
    """
    done_urls = {normalise_url(p["url"]) for p in finished} - {None}
    done_titles = {normalise_title(p["title"]) for p in finished} - {None}
    gone_urls, gone_titles = dropped

    prior_by_url = {normalise_url(e.get("url")): e for e in existing if normalise_url(e.get("url"))}
    prior_by_title = {}
    for e in existing:
        # `alias` is the title the line had before scripts/resolve_queue.py replaced it with
        # the one arXiv returned; without it a resolved entry looks brand new on re-import.
        for key in (normalise_title(e.get("title")), normalise_title(e.get("alias"))):
            if key:
                prior_by_title.setdefault(key, e)

    merged: list[dict] = []
    rejected: set = set()
    by_url: dict[str, dict] = {}
    by_title: dict[str, dict] = {}
    from collections import Counter

    stats = {
        "dropped_finished": 0, "duplicates": 0, "tombstoned": 0, "new": 0,
        "not_papers": Counter(),
    }

    for rows in sources:
        for row in rows:
            row = dict(row)
            # Carry over anything resolve_queue.py or next_paper.py wrote on a previous run,
            # and do it *before* the keys are computed: a lookup that replaced the title and
            # added a URL is exactly the case where the raw export line no longer matches
            # itself, and keying off the raw values would file it as a second paper.
            prior = (
                prior_by_url.get(normalise_url(row["url"]))
                or prior_by_title.get(normalise_title(row["title"]))
                or prior_by_title.get(normalise_title(row.get("alias")))
            )
            if prior is not None:
                for field in KEEP_FIELDS:
                    if prior.get(field) not in (None, 0, [], False):
                        row[field] = prior[field]
                if prior.get("title") and row["source"] != "papers":
                    row["title"] = prior["title"]
                if prior.get("url") and not row["url"]:
                    row["url"] = prior["url"]

            key_u, key_t = normalise_url(row["url"]), normalise_title(row["title"])
            if key_u in done_urls or key_t in done_titles:
                stats["dropped_finished"] += 1
                continue
            if key_u in gone_urls or key_t in gone_titles:
                stats["tombstoned"] += 1
                continue
            # Never filter out something already accepted or marked by hand — a rule should
            # not overrule a decision.
            if not (row.get("curated") or row.get("starred") or row.get("taken")):
                why = not_a_paper(row)
                if why:
                    # Count papers, not sightings: the same patent arrives from the queue
                    # and from the mail, and reporting it twice reads like twice the damage.
                    if (key_u or key_t) not in rejected:
                        rejected.add(key_u or key_t)
                        stats["not_papers"][why] += 1
                    continue
            seen = by_url.get(key_u) or by_title.get(key_t)
            if seen is not None:
                stats["duplicates"] += 1
                seen["tags"] = list(dict.fromkeys(seen["tags"] + row["tags"]))[:MAX_TAGS]
                seen["starred"] = seen["starred"] or row["starred"]
                seen["curated"] = seen.get("curated") or row.get("curated")
                seen["slug"] = seen.get("slug") or row.get("slug")
                # starred/flagged/siblings are derived from the alert mail, so a Scholar
                # sighting is authoritative about them. Without this, an entry flagged by an
                # earlier run keeps that flag after the mail says it is plainly `starred`,
                # and collects both boosts.
                if row["source"] == "scholar" and (row.get("starred") or row.get("flagged")):
                    if row.get("starred"):
                        seen["flagged"], seen["siblings"] = False, None
                    else:
                        seen["flagged"], seen["siblings"] = True, row.get("siblings")
                else:
                    seen["flagged"] = seen.get("flagged") or row.get("flagged")
                    seen["siblings"] = seen.get("siblings") or row.get("siblings")
                seen["alert"] = seen.get("alert") or row.get("alert")
                seen["labels"] = list(
                    dict.fromkeys((seen.get("labels") or []) + (row.get("labels") or []))
                )
                seen["authors"] = seen["authors"] or row["authors"]
                seen["year"] = seen["year"] or row["year"]
                seen["url"] = seen["url"] or row["url"]
                # A paper written down twice takes its most recent sighting: noting it
                # again in this year's list is the interest signal, not the first time.
                if row["added"] and (not seen["added"] or row["added"] > seen["added"]):
                    seen["added"], seen["added_est"] = row["added"], row["added_est"]
                continue

            row["added"] = row["added"] or today
            row.setdefault("strikes", 0)
            if prior is None and existing:
                stats["new"] += 1
            merged.append(row)
            if key_u:
                by_url[key_u] = row
            if key_t:
                by_title[key_t] = row
    return merged, stats


def clean(row: dict) -> dict:
    """Emit a tidy entry: no false flags, no null noise."""
    out: dict = {"title": row["title"], "url": row["url"]}
    if row.get("authors"):
        out["authors"] = row["authors"]
    if row.get("year"):
        out["year"] = int(row["year"])
    out["source"] = row["source"]
    out["added"] = row["added"].isoformat() if row.get("added") else None
    if row.get("added_est"):
        out["added_est"] = True
    for flag in ("starred", "curated", "flagged"):
        if row.get(flag):
            out[flag] = True
    if row.get("flagged") and row.get("siblings"):
        out["siblings"] = int(row["siblings"])
    if row.get("alert"):
        out["alert"] = row["alert"]
    if row.get("labels"):
        out["labels"] = row["labels"]
    if row.get("tags"):
        out["tags"] = row["tags"]
    if row.get("slug"):
        out["slug"] = row["slug"]
    out["strikes"] = int(row.get("strikes") or 0)
    if row.get("weight"):
        out["weight"] = row["weight"]
    if row.get("alias"):
        out["alias"] = row["alias"]
    if row.get("unresolved"):
        out["unresolved"] = True
    if row.get("taken"):
        out["taken"] = row["taken"]
    return out


def write_queue(rows: list[dict]) -> None:
    body = yaml.safe_dump(
        [clean(r) for r in rows], sort_keys=False, allow_unicode=True, width=10_000
    )
    QUEUE.write_text(f"{HEADER}\n{body}", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--keep", type=Path, help="path to the Google Keep markdown dump")
    parser.add_argument("--bib", type=Path, help="path to a Zotero BibTeX export")
    parser.add_argument(
        "--mbox", type=Path, help="path to a Gmail Takeout .mbox of Google Scholar alerts"
    )
    parser.add_argument(
        "--all-senders",
        action="store_true",
        help="with --mbox, don't filter to Google Scholar's alert addresses",
    )
    parser.add_argument(
        "--fresh",
        action="store_true",
        help="ignore the existing queue instead of preserving strikes and deadlines",
    )
    args = parser.parse_args()

    today = dt.date.today()
    existing = []
    if QUEUE.exists() and not args.fresh:
        existing = yaml.safe_load(QUEUE.read_text(encoding="utf-8")) or []

    unfinished, finished = read_papers()
    # Most-considered first: the front matter of a real folder beats the queue's copy of it,
    # the queue beats the curated backlog, and the raw exports come last.
    sources = [unfinished, read_existing(existing), read_backlog()]
    counts = {"papers": len(unfinished), "queue": len(existing), "backlog": len(sources[2])}

    if args.keep:
        rows = read_keep(args.keep, today)
        sources.append(rows)
        counts["keep"] = len(rows)
    if args.mbox:
        rows = read_mbox(args.mbox, args.all_senders)
        sources.append(rows)
        counts["scholar"] = len(rows)
    if args.bib:
        rows = read_bib(args.bib)
        sources.append(rows)
        counts["zotero"] = len(rows)

    merged, stats = merge(sources, finished, existing, journal.dropped_keys(), today)
    write_queue(merged)

    print(f"wrote {QUEUE.relative_to(ROOT)} — {len(merged)} papers in the queue")
    for name, n in counts.items():
        print(f"  {n:>5} from {name}")
    print(f"  {stats['duplicates']:>5} duplicates folded in")
    if existing:
        print(f"  {stats['new']:>5} new since the last run")
    print(f"  {stats['dropped_finished']:>5} skipped (already reviewed)")
    if stats["tombstoned"]:
        print(f"  {stats['tombstoned']:>5} skipped (in _data/dropped.yml)")
    junk = sum(stats["not_papers"].values())
    if junk:
        top = ", ".join(f"{n} {k}" for k, n in stats["not_papers"].most_common(4))
        print(f"  {junk:>5} skipped (not papers: {top}...)")
    no_url = sum(1 for r in merged if not r["url"])
    no_title = sum(1 for r in merged if not r["title"])
    half = sum(1 for r in merged if r.get("slug"))
    print(f"  {half:>5} already have a folder under _papers/")
    if no_url or no_title:
        print(f"  {no_url:>5} without a URL, {no_title} without a title "
              f"— run: python scripts/resolve_queue.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
