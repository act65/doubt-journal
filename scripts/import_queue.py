#!/usr/bin/env python3
"""Build the reading queue from the places papers actually pile up.

Reads, in order of how much the entry has already been thought about:

  _papers/*/index.md      unfinished reviews — a folder exists, the finished review doesn't
  _data/backlog.yml       the hand-curated shortlist (if it is still around)
  keep-dump.md            Google Keep lists, newest list first
  *.mbox                  Google Scholar alert mail, straight out of Gmail Takeout
  all-zotero.bib          the whole Zotero library

and writes one deduplicated ``_data/queue.yml``. Finished reviews (journal.is_finished)
are dropped: they are not waiting to be read any more.

    python scripts/import_queue.py --keep ~/Downloads/keep-dump.md \\
        --bib ~/Downloads/all-zotero.bib --mbox ~/Downloads/scholar.mbox

Nothing here touches the network. Entries that arrive without a title or without a URL stay
that way; `python scripts/resolve_queue.py` is the separate, opt-in step that looks them up.

Rerunning is safe, with or without the export flags: the queue as it stands is folded back in
ahead of the exports, so strikes, deadlines and hand-edited titles survive (matched by
normalised URL, then title, then the `alias` a lookup left behind) and only genuinely new
papers are added. `--fresh` is the one that starts over.

    python scripts/import_queue.py     # just re-sync _papers/ and drop anything now finished
"""

